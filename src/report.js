import { SEVERITY_ORDER, severityColor, c } from './util.js';

function gradeColor(score) {
  if (score >= 85) return c.green;
  if (score >= 70) return c.yellow;
  return c.red;
}

export function printTerminal(result) {
  const out = [];
  out.push('');
  out.push(`  ${c.bold('slophound')} ${c.gray(`v${result.version}`)} — AI slop scanner`);
  out.push('');
  const sc = `${result.score}/100`;
  out.push(`  Score   ${gradeColor(result.score)(c.bold(sc))}  ${c.bold(`(${result.grade})`)}`);
  out.push(
    c.gray(
      `  Scanned ${result.files} files · ${result.lines.toLocaleString('en-US')} lines · ${result.rulesRun} rules · ${result.findings.length} findings`
    )
  );
  out.push('');

  if (result.findings.length === 0) {
    out.push(c.green('  Clean. No slop detected.'));
    out.push('');
    return console.log(out.join('\n'));
  }

  const byRule = new Map();
  for (const f of result.findings) {
    const arr = byRule.get(f.rule) ?? [];
    arr.push(f);
    byRule.set(f.rule, arr);
  }
  const sorted = [...byRule.entries()].sort(
    (a, b) => SEVERITY_ORDER[b[1][0].severity] - SEVERITY_ORDER[a[1][0].severity] || a[0].localeCompare(b[0])
  );

  for (const [ruleId, list] of sorted) {
    const sev = list[0].severity;
    out.push(`${severityColor(sev)('  ' + sev.toUpperCase().padEnd(8))} ${c.bold(ruleId)} ${c.gray(`· ${list.length} finding${list.length > 1 ? 's' : ''}`)}`);
    const shown = list.slice(0, 8);
    for (const f of shown) {
      out.push(`    ${f.file}:${c.bold(String(f.line))}`);
      out.push(c.gray(`      ${f.message}`));
      if (f.snippet) out.push(c.gray(`      | ${f.snippet}`));
    }
    if (list.length > shown.length) out.push(c.gray(`    ... and ${list.length - shown.length} more`));
    out.push('');
  }
  console.log(out.join('\n'));
}

export function toMarkdown(result) {
  const lines = [];
  lines.push(`# SlopHound report`);
  lines.push('');
  lines.push(
    `**Score:** ${result.score}/100 (${result.grade}) · **Files:** ${result.files} · **Lines:** ${result.lines.toLocaleString('en-US')} · **Findings:** ${result.findings.length}`
  );
  lines.push('');
  if (result.findings.length === 0) {
    lines.push('No slop detected. Clean.');
    return lines.join('\n') + '\n';
  }
  lines.push('| Severity | Rule | Location | Message |');
  lines.push('|---|---|---|---|');
  for (const f of result.findings) {
    const msg = String(f.message).replace(/\|/g, '\\|');
    lines.push(`| ${f.severity} | ${f.rule} | ${f.file}:${f.line} | ${msg} |`);
  }
  lines.push('');
  lines.push(`_Generated by slophound v${result.version} — zero dependencies, fully offline._`);
  return lines.join('\n') + '\n';
}

export function summarize(findings) {
  const byRule = {};
  const bySeverity = {};
  for (const f of findings) {
    byRule[f.rule] = (byRule[f.rule] ?? 0) + 1;
    bySeverity[f.severity] = (bySeverity[f.severity] ?? 0) + 1;
  }
  return { byRule, bySeverity };
}
